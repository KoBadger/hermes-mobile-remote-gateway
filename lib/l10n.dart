import 'package:flutter/widgets.dart';

/// Languages the app ships. Arabic is the original UI; English is a plain
/// translation over the very same widget tree, so there is only one set of
/// screens and only the strings and the text direction change.
enum AppLang { ar, en }

/// Minimal, dependency-free localization.
///
/// Two flat tables keyed by a dotted id. [t] picks the table, then substitutes
/// `{name}` placeholders, so a call site stays a single expression and can be
/// used inline in `Text`, `tooltip:`, `hintText:` and friends.
///
/// The app follows the device locale: Arabic when the phone's preferred
/// language is Arabic, English otherwise (English is the fallback, including
/// for every unsupported locale). Force one language with [current] before
/// `runApp`, or at runtime through [setLang].
