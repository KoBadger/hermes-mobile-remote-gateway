  L._();

  /// Active language. Settled once at startup from the device locale.
  static AppLang current = AppLang.en;

  static bool get isEnglish => current == AppLang.en;

  /// Text direction for the active language: the app root wraps its tree in a
  /// [Directionality] built from this, so Arabic stays RTL and English runs LTR
  /// through the same widgets.
  static TextDirection get dir => isEnglish ? TextDirection.ltr : TextDirection.rtl;

  static Locale get locale => Locale(isEnglish ? 'en' : 'ar');

  static const List<Locale> supportedLocales = [Locale('en'), Locale('ar')];

  /// Picks the app language from the device's preferred locales.
  static void fromLocales(List<Locale> locales) {
    final codes = locales.isEmpty ? const [Locale('en')] : locales;
    current = codes.first.languageCode == 'ar' ? AppLang.ar : AppLang.en;
  }

  static void setLang(AppLang lang) => current = lang;

  /// Looks up [id] in the active language and fills `{name}` placeholders from
  /// [vars]. Unknown ids fall through to Arabic and finally to the id itself so
  /// a missing string is visible instead of crashing.
  static String t(String id, [Map<String, Object?>? vars]) {
    var s = (isEnglish ? en : ar)[id] ?? ar[id] ?? en[id] ?? id;
    if (vars != null && vars.isNotEmpty) {
      for (final e in vars.entries) {
        s = s.replaceAll('{${e.key}}', '${e.value}');
      }
    }
    return s;
  }

