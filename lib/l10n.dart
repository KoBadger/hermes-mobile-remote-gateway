      s.startsWith('فشل') ||
      s.startsWith('Could not') ||
      s.startsWith('Failed') ||
      s.startsWith('Cannot') ||
      s.startsWith('Unable') ||
      s.startsWith('Upload failed') ||
      s.startsWith('Wrong ') ||
      s.startsWith('File rejected') ||
      s.startsWith('No app');

  static bool looksLikeSuccess(String s) =>
      s.startsWith('تم ') || s.startsWith('Copied') || s.startsWith('Steering sent') || s.startsWith('Session pulled');

